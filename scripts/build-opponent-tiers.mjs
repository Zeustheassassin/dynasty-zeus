// Regenerates lib/scouting/opponentTierData.ts — every FBS and FCS team, the
// names it goes by, and its tier (P4 / G5 / FCS) per season — from
// CollegeFootballData's /teams list. Rerun when a new season is charted, or
// after conference realignment.
//
//   node --env-file=.env.local scripts/build-opponent-tiers.mjs 2024 2025 2026
//
// One CFD call per season (the free tier allows ~1000 a month).

import { writeFileSync } from "node:fs";

const P4_CONFERENCES = new Set(["SEC", "Big Ten", "Big 12", "ACC"]);
const P4_INDEPENDENTS = new Set(["Notre Dame"]);

const seasons = process.argv.slice(2).map(Number).filter(Boolean);
const key = process.env.CFD_API_KEY;
if (!seasons.length || !key) {
  console.error("usage: node --env-file=.env.local scripts/build-opponent-tiers.mjs <season> [season ...]  (needs CFD_API_KEY)");
  process.exit(1);
}

function tierOf(t) {
  if (t.classification === "fbs") return P4_CONFERENCES.has(t.conference) || P4_INDEPENDENTS.has(t.school) ? "P4" : "G5";
  if (t.classification === "fcs") return "FCS";
  return null;
}

const teams = new Map(); // school -> { names: Set, tiers: {season: tier} }
for (const season of seasons) {
  const res = await fetch(`https://api.collegefootballdata.com/teams?year=${season}`, { headers: { Authorization: `Bearer ${key}` } });
  if (!res.ok) throw new Error(`CFD /teams ${season}: ${res.status}`);
  for (const t of await res.json()) {
    const tier = tierOf(t);
    if (!tier) continue;
    const entry = teams.get(t.school) ?? { names: new Set(), tiers: {} };
    for (const n of [t.school, t.abbreviation, ...(t.alternateNames ?? [])]) if (n) entry.names.add(n);
    entry.tiers[season] = tier;
    teams.set(t.school, entry);
  }
}

const rows = [...teams.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([school, e]) => {
    const tiers = Object.values(e.tiers);
    const t = tiers.every((x) => x === tiers[0]) && tiers.length === seasons.length ? JSON.stringify(tiers[0]) : JSON.stringify(e.tiers);
    const names = [...e.names].filter((n) => n !== school);
    return `  { s: ${JSON.stringify(school)}, a: ${JSON.stringify(names)}, t: ${t} },`;
  });

writeFileSync(
  new URL("../lib/scouting/opponentTierData.ts", import.meta.url),
  `// GENERATED by scripts/build-opponent-tiers.mjs from CollegeFootballData /teams
// (seasons ${seasons.join(", ")}). Don't edit by hand; rerun the script.
//
// s = school, a = other names it goes by, t = tier for every season, or by season
// when it changed (realignment). P4 = SEC, Big Ten, Big 12, ACC and Notre Dame.

export type TierCode = "P4" | "G5" | "FCS";
export interface OpponentTeam { s: string; a: readonly string[]; t: TierCode | Partial<Record<number, TierCode>> }

export const TIER_SEASONS: readonly number[] = ${JSON.stringify(seasons)};

export const OPPONENT_TEAMS: readonly OpponentTeam[] = [
${rows.join("\n")}
];
`,
);
console.log(`wrote ${rows.length} teams for ${seasons.join(", ")}`);
